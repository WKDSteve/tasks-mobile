export const DICTIONARIES = { de, en } as const;
export type Lang = keyof typeof DICTIONARIES;

export function chooseLang(preferred: readonly string[]): Lang {
  return pickLang(preferred, ['de', 'en'] as const, 'en');
}

export type Translate = (key: TextKey, params?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const dictionary = DICTIONARIES[lang];
  return (key, params = {}) => lookup(dictionary, key, params);
}
